"""
Pipeline runner — drives the real acquisition pipeline (focus_map.py via
main_live_qc.py) as a SUBPROCESS, instead of the GUI calling msem.* inline.

Why a subprocess (not in-process import):
  - focus_map.py / main_live_qc.py are standalone scripts: each builds its own
    MSEMConnection and main_live_qc spawns its own matplotlib LiveQC subprocess.
    Importing them into the Qt event loop would fight the GUI's own engine
    connection and the matplotlib child. Running them as a child process is
    exactly how the user runs them from a terminal today — zero interference.
  - The GUI just: builds a config JSON, launches `python main_live_qc.py` with
    MSEM_CONFIG_JSON pointing at it, tails the merged stdout/stderr (the same
    text you'd see in the terminal + per-section console.log), and parses the
    [Regions]/[Region]/[AcqTile]/[LiveQC] lines into progress signals.

Config JSON shape consumed by focus_map.apply_external_config_override() and
main_live_qc._apply_live_qc_config_override():
    {"focus_map": { ...CONFIG overrides... },
     "live_qc":   { ...LIVE_QC_CONFIG overrides... }}
"""
from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path
from typing import Any, Dict, Optional

from PySide6.QtCore import QObject, QProcess, QProcessEnvironment, Signal


# ---------------------------------------------------------------------------
# Pure UI -> config mapping (no Qt, unit-testable)
# ---------------------------------------------------------------------------

# Scan-rate combo text "Comb"/"Serpentine" -> focus_map route_mode token.
_TRAVEL_MAP = {
    "comb": "COMB",
    "serpentine": "SERPENTINE",
    "snake": "SERPENTINE",
}
# Direction combo text -> focus_map travel_direction token.
_DIRECTION_MAP = {
    "horizontal up": "HORIZONTAL_UP",
    "horizontal down": "HORIZONTAL_DOWN",
    "vertical left": "VERTICAL_LEFT",
    "vertical right": "VERTICAL_RIGHT",
}
# Start-position combo text -> focus_map start_position token.
_START_MAP = {
    "top": "TOP",
    "bottom": "BOTTOM",
    "bottom left": "BOTTOM",
    "bottom right": "BOTTOM",
    "top left": "TOP",
    "top right": "TOP",
}

# Reverse of the three maps above, for config_to_ui() - only the canonical
# display text each token should round-trip to (the aliases above, e.g.
# "snake"/"bottom left", only exist as forgiving INPUT spellings and have no
# single correct reverse).
_TRAVEL_MAP_REV = {"SERPENTINE": "Serpentine", "COMB": "Comb"}
_DIRECTION_MAP_REV = {
    "VERTICAL_LEFT": "Vertical Left", "VERTICAL_RIGHT": "Vertical Right",
    "HORIZONTAL_UP": "Horizontal Up", "HORIZONTAL_DOWN": "Horizontal Down",
}
_START_MAP_REV = {"TOP": "Top", "BOTTOM": "Bottom"}

# focus_map CONFIG keys build_run_config() maps from a differently-named UI
# key (or a transformed value) - everything else round-trips by identity.
# {config_key: (ui_key, inverse_transform | None)}
_FM_KEY_MAP = {
    "json_file": ("imaging_json_path", None),
    "region_name_filter": ("region_name_filter", None),
    "process_all_regions": ("process_all_regions", None),
    "region_name": ("region_name", None),
    "output_root": ("output_root", None),
    "czi_name": ("czi_name", None),
    "prefix_base": ("prefix_base", None),
    "combo_format": ("combo_format", None),
    "acq_pixel_size_nm": ("acq_pixel_size_nm", float),
    "acq_scan_speed": ("acq_scan_speed", int),
    "acq_width": ("acq_width", int),
    "acq_height": ("acq_height", int),
    "roi_hex_overlap": ("mfov_overlap_pct", lambda v: float(v) * 100.0),
    "inner_sfoverlap_um": ("sfov_overlap_um", float),
    "route_mode": ("travel_pattern", lambda v: _TRAVEL_MAP_REV.get(str(v).upper())),
    "travel_direction": ("travel_direction", lambda v: _DIRECTION_MAP_REV.get(str(v).upper())),
    "start_position": ("start_position", lambda v: _START_MAP_REV.get(str(v).upper())),
    "prev_focusmap_dir": ("prev_focusmap_dir", None),
    "preflight_skip_missing": ("preflight_skip_missing", bool),
    "skip_already_imaged": ("skip_already_imaged", bool),
    "retake_regions_file": ("retake_regions_file", None),
    "plane_update_method": ("plane_update_method", None),
    "initial_ol_mode": ("initial_ol_mode", None),
    "best_point_metric": ("best_point_metric", None),
    # Only ever set via fm_extra (see himc_page._build_ui_dict) - no `put()`
    # counterpart in build_run_config, but it has its own dedicated GUI field
    # (edit_wafer_fiducial), so it round-trips the same way as the ones above.
    "wafer_fiducial_ol_file": ("wafer_fiducial_ol_file", None),
    # route_source is always forced to "REBUILD" alongside route_mode - no
    # independent UI state, so it's neither restored nor exposed here.
    "route_source": (None, None),
    # Cleared to {} automatically whenever prev_focusmap_dir is set (see
    # build_run_config) - not independent user input, never round-tripped.
    "prev_focusmap_by_region": (None, None),
    # Always regenerated by the GUI itself from repo_root - never restored.
    "acquire_script_path": (None, None),
}

# live_qc CONFIG keys with a differently-named UI key (all qc_* here are a
# straight rename, no value transform).
_LQ_KEY_MAP = {
    "low_quality_threshold": ("qc_low_quality_threshold", float),
    "high_quality_threshold": ("qc_high_quality_threshold", float),
    "focus_color_mode": ("qc_focus_color_mode", None),
    "num_extra_beams": ("qc_num_extra_beams", int),
    "beam_selection_mode": ("qc_beam_selection_mode", None),
    "beam_outlier_alert_enabled": ("qc_beam_outlier_alert_enabled", bool),
    "beam_outlier_mad_sigma": ("qc_beam_outlier_mad_sigma", float),
    "beam_outlier_min_beams": ("qc_beam_outlier_min_beams", int),
    "jitter_warn_threshold": ("qc_jitter_warn_threshold", float),
    "outside_roi_sat_threshold": ("qc_outside_roi_sat_threshold", float),
    "save_every": ("qc_save_every", int),
    "acquire_script_path": (None, None),  # always regenerated, never restored
}


def config_to_ui(cfg: Dict[str, Any]) -> Dict[str, Any]:
    """Inverse of build_run_config(): given the {focus_map, live_qc} config
    dict (e.g. loaded back from a previous run's msem_run_config.json),
    return a flat UI-shaped dict using the same keys build_run_config()
    accepts as input - so the two stay mechanically in sync instead of
    drifting apart as separate hand-maintained mappings.

    Any focus_map/live_qc key with no explicit UI counterpart (the
    data-driven "extra param" groups, or a genuine ad-hoc override) is
    passed through verbatim in "fm_rest"/"lq_rest" under its OWN config-key
    name, for the caller to match against its own extra-widget registry
    and/or fall back to displaying as a raw override - so a setting from an
    older or hand-edited config is never silently dropped on restore, even
    if this GUI doesn't have a dedicated widget for it (yet)."""
    fm = dict(cfg.get("focus_map") or {})
    lq = dict(cfg.get("live_qc") or {})
    ui: Dict[str, Any] = {}

    for cfg_key, (ui_key, inv) in _FM_KEY_MAP.items():
        if cfg_key in fm:
            v = fm.pop(cfg_key)
            if ui_key is None:
                continue
            try:
                ui[ui_key] = inv(v) if inv else v
            except Exception:
                pass  # unparseable/stale value - leave the widget at its default

    for cfg_key, (ui_key, inv) in _LQ_KEY_MAP.items():
        if cfg_key in lq:
            v = lq.pop(cfg_key)
            if ui_key is None:
                continue
            try:
                ui[ui_key] = inv(v) if inv else v
            except Exception:
                pass

    ui["fm_rest"] = fm
    ui["lq_rest"] = lq
    return ui


def build_run_config(ui: Dict[str, Any]) -> Dict[str, Any]:
    """Map a flat dict of UI values to the {focus_map, live_qc} config the
    pipeline consumes. Only keys the user actually set should be present in
    `ui`; everything omitted falls back to the pipeline's hardcoded defaults.

    Recognised `ui` keys (all optional):
      imaging_json_path, output_root, czi_name, prefix_base, combo_format,
      region_name_filter, process_all_regions, region_name,
      acq_pixel_size_nm, acq_scan_speed, acq_width, acq_height,
      mfov_overlap_pct, sfov_overlap_um,
      travel_pattern, travel_direction, start_position,
      prev_focusmap_by_region, plane_update_method, initial_ol_mode,
      # live_qc:
      qc_low_quality_threshold, qc_high_quality_threshold, qc_focus_color_mode,
      qc_num_extra_beams, qc_beam_selection_mode,
      qc_beam_outlier_alert_enabled, qc_beam_outlier_mad_sigma, qc_beam_outlier_min_beams,
      qc_jitter_warn_threshold, qc_outside_roi_sat_threshold, qc_save_every,
      qc_extra (dict, merged verbatim into live_qc)
    """
    fm: Dict[str, Any] = {}

    def put(key, ui_key, transform=None):
        if ui_key in ui and ui[ui_key] is not None:
            v = ui[ui_key]
            fm[key] = transform(v) if transform else v

    # imaging JSON + region selection
    put("json_file", "imaging_json_path")
    put("region_name_filter", "region_name_filter")
    put("process_all_regions", "process_all_regions")
    put("region_name", "region_name")

    # output
    put("output_root", "output_root")
    put("czi_name", "czi_name")
    put("prefix_base", "prefix_base")
    put("combo_format", "combo_format")

    # scan
    put("acq_pixel_size_nm", "acq_pixel_size_nm", float)
    put("acq_scan_speed", "acq_scan_speed", int)
    put("acq_width", "acq_width", int)
    put("acq_height", "acq_height", int)

    # overlap
    if ui.get("mfov_overlap_pct") is not None:
        # focus_map roi_hex_overlap is a 0..0.5 fraction; UI gives percent.
        fm["roi_hex_overlap"] = float(ui["mfov_overlap_pct"]) / 100.0
    put("inner_sfoverlap_um", "sfov_overlap_um", float)

    # route
    if ui.get("travel_pattern"):
        fm["route_mode"] = _TRAVEL_MAP.get(str(ui["travel_pattern"]).strip().lower(), "SERPENTINE")
        fm["route_source"] = "REBUILD"
    if ui.get("travel_direction"):
        fm["travel_direction"] = _DIRECTION_MAP.get(str(ui["travel_direction"]).strip().lower(), "VERTICAL_LEFT")
    if ui.get("start_position"):
        fm["start_position"] = _START_MAP.get(str(ui["start_position"]).strip().lower(), "TOP")

    # advanced (optional)
    put("prev_focusmap_by_region", "prev_focusmap_by_region")
    put("prev_focusmap_dir", "prev_focusmap_dir")  # folder of prev_focusmap .txt
    # If the user gave a prev_focusmap FOLDER (and no explicit per-region dict),
    # make folder mode authoritative by clearing focus_map's HARDCODED
    # prev_focusmap_by_region. Otherwise that dict's same-section fallback
    # hijacks the region (e.g. S6R2 -> dict's S6R1 entry) and resolves a stale
    # RELATIVE filename like 'w13_s6.txt' against the cwd instead of looking in
    # the folder the user actually picked.
    if fm.get("prev_focusmap_dir") and "prev_focusmap_by_region" not in fm:
        fm["prev_focusmap_by_region"] = {}
    put("preflight_skip_missing", "preflight_skip_missing")  # all-region focusmap preflight policy
    # Skip regions already successfully imaged in an earlier batch under the
    # same output_root (see live_qc_support.compute_regions_to_image), plus
    # anything explicitly listed in retake_regions_file (defaults to
    # <output_root>/retake_regions.txt if not given here).
    put("skip_already_imaged", "skip_already_imaged", bool)
    put("retake_regions_file", "retake_regions_file")
    put("plane_update_method", "plane_update_method")
    put("initial_ol_mode", "initial_ol_mode")
    put("best_point_metric", "best_point_metric")
    # any extra focus_map keys passed verbatim
    extra_fm = ui.get("fm_extra")
    if isinstance(extra_fm, dict):
        fm.update(extra_fm)

    # ---- live_qc section ----
    lq: Dict[str, Any] = {}

    def putq(key, ui_key, transform=None):
        if ui_key in ui and ui[ui_key] is not None:
            v = ui[ui_key]
            lq[key] = transform(v) if transform else v

    # Path to the focus_map.py the wrapper should load. Defaults in
    # main_live_qc.py to a hardcoded D:\ path; the GUI overrides it to the
    # co-located focus_map.py so the subprocess always loads the right script.
    putq("acquire_script_path", "acquire_script_path")
    putq("low_quality_threshold", "qc_low_quality_threshold", float)
    putq("high_quality_threshold", "qc_high_quality_threshold", float)
    putq("focus_color_mode", "qc_focus_color_mode")
    putq("num_extra_beams", "qc_num_extra_beams", int)
    putq("beam_selection_mode", "qc_beam_selection_mode")
    putq("beam_outlier_alert_enabled", "qc_beam_outlier_alert_enabled", bool)
    putq("beam_outlier_mad_sigma", "qc_beam_outlier_mad_sigma", float)
    putq("beam_outlier_min_beams", "qc_beam_outlier_min_beams", int)
    putq("jitter_warn_threshold", "qc_jitter_warn_threshold", float)
    putq("outside_roi_sat_threshold", "qc_outside_roi_sat_threshold", float)
    putq("save_every", "qc_save_every", int)
    extra_lq = ui.get("qc_extra")
    if isinstance(extra_lq, dict):
        lq.update(extra_lq)

    out: Dict[str, Any] = {}
    if fm:
        out["focus_map"] = fm
    if lq:
        out["live_qc"] = lq
    return out


