# QProcess-based subprocess driver
# ---------------------------------------------------------------------------

class PipelineRunner(QObject):
    """Launches `python main_live_qc.py` as a child process and surfaces its
    output + progress as Qt signals. One runner drives one acquisition run."""

    log_line = Signal(str)                 # a single line of subprocess output
    started = Signal()                     # process launched OK
    region_total = Signal(int)             # total regions to process
    region_order = Signal(list)            # FULL ordered list of region names about to run
    region_started = Signal(str, int)      # region_name, region_idx (1-based)
    tile_progress = Signal(int, int)       # order, total (within current region)
    qc_tile = Signal(int)                  # tile_idx queued to LiveQC
    beam_arc = Signal(str)                 # a [BeamArc] status line (arc detected / recovery)
    region_done = Signal(str)              # region_name finished
    region_failed = Signal(str)            # region_name raised an exception mid-run
    region_skipped = Signal(str)           # region_name dropped by preflight (missing prev-focusmap)
    stage_z = Signal(float)                # live stage Z (um) readback after every stage move
    finished = Signal(int)                 # process exit code (0 == clean)
    error = Signal(str)                    # fatal launch / process error

    _RE_REGIONS_TOTAL = re.compile(r"\[Regions\]\s+Will process\s+(\d+)\s+region")
    # focus_map.py prints the FULL planned order as a Python list repr, before
    # any hardware work starts - see "[Regions] Will process N region(s)...:
    # [...]" in focus_map.main(). ast.literal_eval (not eval) turns that list
    # repr back into real strings safely.
    _RE_REGIONS_ORDER = re.compile(
        r"\[Regions\]\s+Will process\s+\d+\s+region\(s\).*?:\s*(\[.*\])\s*$")
    # If preflight drops some regions (missing prev-focusmap), it reprints the
    # FINAL, filtered order it's actually proceeding with - see
    # preflight_resolve_prev_focusmaps(). Supersedes _RE_REGIONS_ORDER's list
    # when both appear (preflight always runs after the first print).
    _RE_PREFLIGHT_PROCEEDING = re.compile(
        r"\[Preflight\]\s+proceeding with\s+\d+\s+region\(s\):\s*(\[.*\])\s*$")
    # Region names can contain spaces (e.g. "S24R1 (2)" for a section's 2nd
    # ROI) - (\S+) would truncate those at the first space, potentially
    # colliding with an unrelated region actually named "S24R1". Each pattern
    # instead captures non-greedily up to whatever fixed text actually
    # follows the name in that specific print statement.
    _RE_PREFLIGHT_SKIP = re.compile(r"\[Preflight\]\s+WARNING:\s+skipping region\s+(.+?)\s+\(no prev focusmap:")
    _RE_REGION_START = re.compile(r"\[Region\]\s+START\s+region_name=(.+?)\s+region_idx=(\d+)")
    _RE_REGION_DONE = re.compile(r"\[Region\]\s+DONE\s+region_name=(.+)$")
    _RE_REGION_FAILED = re.compile(r"\[Region\]\s+FAILED\s+region_name=(.+?)\s+-\s")
    # Distinct from a preflight skip (missing prev-focusmap, caught before any
    # hardware work) - this fires mid-run when _abort_if_stage_z_unsafe()
    # refuses to image a region because the stage Z was too close to 0 to be
    # a real height on this wafer. Same region_skipped signal either way.
    _RE_REGION_RUNTIME_SKIP = re.compile(r"\[Region\]\s+SKIPPED\s+region_name=(.+?)\s+-\s")
    _RE_ACQ_TILE = re.compile(r"\[AcqTile\]\s+order=(\d+)/(\d+)")
    _RE_QC_TILE = re.compile(r"\[LiveQC\]\s+queued tile\s+(\d+)")
    _RE_BEAM_ARC = re.compile(r"\[BeamArc\]\s+(.*)")
    # Printed by stage_move_xy_z() after EVERY stage move (see focus_map.py) -
    # lets the GUI watch the live stage Z even across moves that never
    # explicitly command a Z target, where a drift toward a low/parked Z
    # would otherwise go unnoticed until something downstream fails.
    _RE_STAGE_Z = re.compile(r"\[StageZ\]\s+current Z=(-?[\d.]+)\s+um")

    def __init__(self, parent: Optional[QObject] = None):
        super().__init__(parent)
        self._proc: Optional[QProcess] = None
        self._buf = ""
        self._config_path = ""

    # -- state --------------------------------------------------------------
    def is_running(self) -> bool:
        return self._proc is not None and self._proc.state() != QProcess.NotRunning

    @property
    def config_path(self) -> str:
        return self._config_path

    # -- launch -------------------------------------------------------------
    def start(
        self,
        config: Dict[str, Any],
        *,
        workdir: str,
        config_path: Optional[str] = None,
        python_exe: Optional[str] = None,
        script: str = "main_live_qc.py",
        args: Optional[list] = None,
    ) -> bool:
        """Write `config` to JSON and spawn the pipeline. Returns False if a run
        is already in progress or the config couldn't be written.

        `args` overrides the child argv (defaults to just [script]). The SFN
        calibration uses it to launch `auto_stage_calib.py --markers ... --affine_out ...`
        which is argparse-driven (it does NOT read MSEM_CONFIG_JSON)."""
        if self.is_running():
            self.error.emit("A pipeline run is already in progress.")
            return False

        workdir = str(workdir)
        if config_path is None:
            config_path = os.path.join(workdir, "msem_run_config.json")
        self._config_path = config_path
        try:
            Path(config_path).parent.mkdir(parents=True, exist_ok=True)
            with open(config_path, "w", encoding="utf-8") as f:
                json.dump(config, f, indent=2)
        except Exception as exc:
            self.error.emit(f"Failed to write config {config_path}: {exc}")
            return False

        self._buf = ""
        proc = QProcess(self)
        proc.setWorkingDirectory(workdir)
        proc.setProcessChannelMode(QProcess.MergedChannels)  # interleave stderr+stdout

        env = QProcessEnvironment.systemEnvironment()
        env.insert("MSEM_CONFIG_JSON", config_path)
        env.insert("PYTHONUNBUFFERED", "1")  # live line-buffered output
        proc.setProcessEnvironment(env)

        proc.readyReadStandardOutput.connect(self._on_stdout)
        proc.finished.connect(self._on_finished)
        proc.errorOccurred.connect(self._on_proc_error)
        proc.started.connect(self.started)

        exe = python_exe or sys.executable
        argv = args if args is not None else [script]
        proc.setProgram(exe)
        proc.setArguments(argv)
        self._proc = proc
        self.log_line.emit(
            f"[runner] launch: {exe} {' '.join(argv)}  (cwd={workdir})  "
            f"MSEM_CONFIG_JSON={config_path}"
        )
        proc.start()
        return True

    # -- stop ---------------------------------------------------------------
    def request_stop(self) -> None:
        """Graceful stop: send SIGINT so main_live_qc.py's signal handler can
        flush the in-flight tile + shut down the LiveQC subprocesses. Falls
        back to QProcess.terminate() if SIGINT can't be delivered."""
        if not self.is_running():
            return
        self.log_line.emit("[runner] stop requested — sending interrupt (graceful)")
        pid = int(self._proc.processId())
        try:
            import signal as _sig
            os.kill(pid, _sig.SIGINT)
        except Exception:
            try:
                self._proc.terminate()
            except Exception as exc:
                self.error.emit(f"terminate failed: {exc}")

    def kill(self) -> None:
        if self.is_running():
            self._proc.kill()

    # -- internal -----------------------------------------------------------
    def _on_stdout(self) -> None:
        if not self._proc:
            return
        chunk = bytes(self._proc.readAllStandardOutput()).decode("utf-8", errors="replace")
        self._buf += chunk
        self._drain_complete_lines()

    def _drain_complete_lines(self) -> None:
        while "\n" in self._buf:
            line, self._buf = self._buf.split("\n", 1)
            self._handle_line(line.rstrip("\r"))

    def _handle_line(self, line: str) -> None:
        if line == "":
            return
        self.log_line.emit(line)

        # The "Will process" line carries BOTH the count (_RE_REGIONS_TOTAL)
        # and the full ordered name list (_RE_REGIONS_ORDER) - check both
        # against it instead of returning after the first match, since one
        # pattern is a strict prefix of the other.
        m = self._RE_REGIONS_TOTAL.search(line)
        if m:
            self.region_total.emit(int(m.group(1)))
        m = self._RE_REGIONS_ORDER.search(line)
        if m:
            try:
                import ast
                names = ast.literal_eval(m.group(1))
                if isinstance(names, list):
                    self.region_order.emit([str(n) for n in names])
            except Exception:
                pass
            return

        m = self._RE_PREFLIGHT_PROCEEDING.search(line)
        if m:
            try:
                import ast
                names = ast.literal_eval(m.group(1))
                if isinstance(names, list):
                    self.region_order.emit([str(n) for n in names])
            except Exception:
                pass
            return
        m = self._RE_PREFLIGHT_SKIP.search(line)
        if m:
            self.region_skipped.emit(m.group(1))
            return
        m = self._RE_REGION_START.search(line)
        if m:
            self.region_started.emit(m.group(1), int(m.group(2)))
            return
        m = self._RE_REGION_DONE.search(line)
        if m:
            self.region_done.emit(m.group(1))
            return
        m = self._RE_REGION_FAILED.search(line)
        if m:
            self.region_failed.emit(m.group(1))
            return
        m = self._RE_REGION_RUNTIME_SKIP.search(line)
        if m:
            self.region_skipped.emit(m.group(1))
            return
        m = self._RE_ACQ_TILE.search(line)
        if m:
            self.tile_progress.emit(int(m.group(1)), int(m.group(2)))
            return
        m = self._RE_QC_TILE.search(line)
        if m:
            self.qc_tile.emit(int(m.group(1)))
            return
        m = self._RE_BEAM_ARC.search(line)
        if m:
            self.beam_arc.emit(m.group(1))
            return
        m = self._RE_STAGE_Z.search(line)
        if m:
            try:
                self.stage_z.emit(float(m.group(1)))
            except Exception:
                pass
            return

    def _on_finished(self, code: int, _status) -> None:
        # QProcess does not reliably guarantee readyReadStandardOutput fires
        # for every byte the child wrote right before exiting - a real run
        # showed the GUI's live region-progress panel stuck one region
        # behind (e.g. "22/23 done") after the process had already exited,
        # because the final "[Region] DONE ..."/"[Regions] N/M region(s)
        # completed..." lines never reached _on_stdout. Drain whatever is
        # still sitting in the process's output buffer here too, not just
        # whatever _on_stdout already moved into self._buf, before treating
        # the run as over.
        if self._proc is not None:
            chunk = bytes(self._proc.readAllStandardOutput()).decode("utf-8", errors="replace")
            self._buf += chunk
        self._drain_complete_lines()
        if self._buf:
            self._handle_line(self._buf)
            self._buf = ""
        self.finished.emit(int(code))
        self._proc = None

    def _on_proc_error(self, err) -> None:
        # err is a QProcess.ProcessError enum; stringify defensively
        self.error.emit(f"QProcess error: {err}")
